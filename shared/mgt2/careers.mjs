// Traveller's careers for the lifepath, Kraken's own tables in the game's
// shape (the procedure is Mongoose Traveller 2E's: qualification, basic
// training, a skill roll a term, survival or a mishap, an event, commission
// and advancement, aging, mustering out). The careers' names are the game's
// common ones; every number, skill list, rank, event and mishap here is
// written for Kraken (no book text). The GM's own Traveller books are the
// game's real tables.
//
// A skill entry: "Pilot" (any speciality, chosen), "Gun Combat (Slug)", "STR +1"
// (a characteristic), or ["Admin", "Advocate"] (one of them, chosen).
// An effect (events, mishaps, benefits): see lifepath.mjs (gain, stat, dm,
// benefit, contact, ally, rival, enemy, injury, life, check, choice, leave,
// promote, commission, prison, credits, lose, item, note).

const t = (...entries) => entries;
const assign = (name, survival, advancement, specialist, desc = "") => ({ name, survival, advancement, specialist, desc });
const ranks = (...rows) => rows.map(([title, bonus = null]) => ({ title, bonus }));
const ev = (text, ...effects) => ({ text, effects });

