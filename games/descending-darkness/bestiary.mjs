const STATS = ["strength", "dexterity", "constitution", "intelligence", "wisdom", "charisma"];
const bonus = (score) => Math.floor((score - 10) / 2);
const XP = { "0": 10, "1/8": 25, "1/4": 50, "1/2": 100, 1: 200, 2: 450, 3: 700, 4: 1100, 5: 1800 };
const avg = (dice) => {
  const match = /(\d+)d(\d+)\s*([+-]\s*\d+)?/.exec(dice);
  return match ? Math.floor(Number(match[1]) * (Number(match[2]) + 1) / 2 + Number((match[3] ?? "0").replace(/\s/g, ""))) : 1;
};
// An attack: "melee" or "ranged", its bonus, reach or range, damage dice and type.
export const hit = (name, kind, toHit, reach, dice, type, extra = "") => ({
  name,
  desc: `${kind === "ranged" ? "Ranged" : "Melee"} Attack Roll: ${toHit >= 0 ? "+" : ""}${toHit}, ${kind === "ranged" ? `range ${reach}` : `reach ${reach}`}. Hit: ${avg(dice)} (${dice}) ${type} damage.${extra ? ` ${extra}` : ""}`,
});

const creature = ({ name, type, size = "Medium", cr, ac, hd, speed = "30 ft.", scores, senses = "", skills = "", languages = "", traits = [], actions = [], text, category = "Creatures", token = "" }) => {
  const [str, dex, con, int, wis, cha] = scores;
  const abilities = Object.fromEntries(STATS.map((stat, index) => [stat, { score: [str, dex, con, int, wis, cha][index], bonus: bonus([str, dex, con, int, wis, cha][index]), savemodifier: 0 }]));
  return {
    name,
    type,
    size,
    cr: String(cr),
    xp: XP[String(cr)] ?? 0,
    ac,
    hp: avg(hd),
    hd: `(${hd})`,
    speed,
    abilities,
    senses,
    skills,
    languages,
    alignment: "",
    initiative: { misc: 0 },
    traits: ids(traits.map(([trait, body]) => ({ name: trait, desc: body }))),
    actions: ids(actions),
    text: md(text),
    ...creatureArt(name, "Descending Darkness Bestiary"),
    ...(token ? { token } : {}),
    __category: category,
  };
};

